export const CASTS = [
  { id: "nutrias", label: "Nutrias" },
  { id: "criaturas", label: "Criaturas" },
  { id: "galaxia", label: "Galaxia" },
];

const KEY = "tower-cast";

export function currentCast() {
  try {
    const v = localStorage.getItem(KEY);
    return CHARACTERS[v] ? v : "nutrias";
  } catch (e) {
    return "nutrias";
  }
}

export function setCast(id) {
  try {
    if (id === "nutrias") localStorage.removeItem(KEY);
    else localStorage.setItem(KEY, id);
  } catch (e) {}
}

function toRects({ rows, palette }) {
  let out = "";
  rows.forEach((row, i) => {
    for (let x = 0; x < row.length; ) {
      const ch = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (palette[ch]) out += `<rect x="${x / 2}" y="${i / 2 - 1}" width="${(end - x) / 2}" height=".5" fill="${palette[ch]}"/>`;
      x = end;
    }
  });
  return out;
}

const drawn = {};

export function characterFor(seed) {
  const cast = currentCast();
  const list = CHARACTERS[cast];
  if (!list) return null;
  const c = list[seed % list.length];
  const key = `${cast}:${c.name}`;
  if (!drawn[key]) drawn[key] = toRects(c);
  return { name: c.name, body: drawn[key], eyes: c.eyes, eyeSize: c.eyeSize || [2, 3], eye: c.eye || "#1b1b1f", glint: c.glint !== false };
}

export function characterEyes(who, look) {
  if (!who.eyes) return "";
  const [w, hgt] = who.eyeSize;
  const px = (x, y, wd = 1, ht = 1, fill = who.eye) => `<rect class="eye" x="${x / 2}" y="${y / 2 - 1}" width="${wd / 2}" height="${ht / 2}" fill="${fill}"/>`;
  return who.eyes
    .map(([x, y]) => {
      if (look === "shut") return px(x - 1, y + hgt - 1, w + 2, 1);
      if (look === "happy") return px(x - 1, y + 1) + px(x, y, w, 1) + px(x + w, y + 1);
      return px(x, y, w, hgt) + (who.glint ? px(x, y, 1, 1, "#fff") : "");
    })
    .join("");
}
